-- Client groups: one account (customer) can own several configs; a group is enabled/disabled as a whole

CREATE TABLE IF NOT EXISTS client_groups (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL COMMENT 'Panel user who owns the group',
  name VARCHAR(255) NOT NULL,
  comment TEXT NULL,
  status ENUM('active', 'disabled') NOT NULL DEFAULT 'active',
  disabled_at TIMESTAMP NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_user_id (user_id),
  INDEX idx_status (status),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET @col_exists := (
  SELECT COUNT(*) FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'vpn_clients' AND COLUMN_NAME = 'group_id'
);
SET @sql := IF(
  @col_exists = 0,
  'ALTER TABLE vpn_clients
     ADD COLUMN group_id INT UNSIGNED NULL AFTER user_id,
     ADD COLUMN disabled_by_group TINYINT(1) NOT NULL DEFAULT 0 COMMENT ''1 = disabled by group switch-off, restored with the group'' AFTER status,
     ADD INDEX idx_group_id (group_id),
     ADD CONSTRAINT fk_vpn_clients_group FOREIGN KEY (group_id) REFERENCES client_groups(id) ON DELETE SET NULL',
  'SELECT 1'
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

